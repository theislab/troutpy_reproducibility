def plot_syngo_ora(
    ora_df: pd.DataFrame,
    top_n_per_cluster: int = 5,
    cmap: str = "RdYlBu_r",
    min_dot_size: float = 30.0,
    max_dot_size: float = 400.0,
    saving_path: str = None,
) -> None:
    """Generates a highly tunable dot plot visualization for multi-term SynGO ORA results,

    filtering for the top hits per cluster and exporting to an editable vector PDF.

    Parameters:
    -----------
    ora_df : pd.DataFrame
        The output DataFrame generated by calculate_syngo_ora function.
    top_n_per_cluster : int, default 5
        The number of top significant pathways to extract per individual cluster profile.
    cmap : str, default 'RdYlBu_r'
        Colormap used to represent the biological Enrichment Ratio.
    min_dot_size : float, default 30.0
        The visual dot display size mapping to the highest (least significant) FDR value.
    max_dot_size : float, default 400.0
        The visual dot display size mapping to the lowest (most significant) FDR value.
    saving_path : str, optional
        File path string where the generated PDF plot should be saved.
    """
    if ora_df is None or ora_df.empty:
        print("Provided DataFrame is empty. Skipping visualization.")
        return

    # --- STEP 1: ISOLATE THE TOP HITS PER CLUSTER ---
    # Sort prioritizing statistical confidence, then group and take top N entries
    top_hits = (
        ora_df.sort_values("p_value", ascending=True)
        .groupby("cluster")
        .head(top_n_per_cluster)
        .copy()
    )

    # Convert positions to strings explicitly to prevent categorical mismatching
    top_hits["cluster"] = top_hits["cluster"].astype(str)
    top_hits["syn_go_term"] = top_hits["syn_go_term"].astype(str)

    # --- STEP 2: CALCULATE MIN-MAX COMPRESSION SCALE FOR FDR SIZES ---
    # Dot size maps onto -log10(FDR), where larger dots indicate higher confidence
    fdr_sizes = top_hits["minus_log10_fdr"].values
    min_f, max_f = fdr_sizes.min(), fdr_sizes.max()

    if max_f == min_f:
        dot_sizes = np.repeat((min_dot_size + max_dot_size) / 2, len(fdr_sizes))
    else:
        # Scale to 0-1 range, then stretch to visual boundaries
        normalized_fdr = (fdr_sizes - min_f) / (max_f - min_f)
        dot_sizes = min_dot_size + (
            normalized_fdr * (max_dot_size - min_dot_size)
        )

    # --- STEP 3: INITIALIZE PLOT ---
    # Determine sizing dynamically based on data dimensionality
    n_clusters = top_hits["cluster"].nunique()
    n_terms = top_hits["syn_go_term"].nunique()
    fig_width = max(8, n_clusters * 1.5)
    fig_height = max(6, n_terms * 0.4)

    fig, ax = plt.subplots(figsize=(fig_width, fig_height))
    sns.set_theme(style="whitegrid")

    # --- STEP 4: RENDER SCATTER MATRIX ---
    scatter = ax.scatter(
        x=top_hits["cluster"],
        y=top_hits["syn_go_term"],
        s=dot_sizes,
        c=top_hits["enrichment_ratio"],
        cmap=cmap,
        edgecolors="black",
        linewidths=0.6,
        zorder=3,
    )

    # Adjust grids to fit beautifully behind data centers
    ax.grid(True, linestyle="--", alpha=0.4, zorder=1)

    # --- STEP 5: COLORBAR TRACK CONFIGURATION ---
    cbar = fig.colorbar(scatter, ax=ax, pad=0.02, shrink=0.7)
    cbar.set_label("Enrichment Ratio (Observed / Expected)", fontsize=11)

    # --- STEP 6: DYNAMIC RE-MAPPED SIGNIFICANCE LEGEND ---
    # Generate 4 evenly distributed key milestones between minimum and maximum FDR values
    fdr_milestones = np.linspace(min_f, max_f, num=4)
    size_milestones = np.linspace(min_dot_size, max_dot_size, num=4)

    legend_markers = [
        ax.scatter(
            [],
            [],
            s=sz,
            c="gray",
            alpha=0.6,
            edgecolors="black",
            linewidths=0.6,
        )
        for sz in size_milestones
    ]

    # Re-convert -log10 values back into localized text thresholds for clarity
    legend_labels = [f"10^(-{val:.1f})" for val in fdr_milestones]

    ax.legend(
        legend_markers,
        legend_labels,
        loc="upper left",
        bbox_to_anchor=(1.25, 1.0),
        title="FDR Adjusted P-value",
        frameon=True,
    )

    # --- STEP 7: TITLES & LABELS ---
    ax.set_title(
        "SynGO Functional Pathway ORA Enrichment Profile",
        fontsize=14,
        pad=18,
        weight="bold",
    )
    ax.set_xlabel("Tissue Structure Groups", fontsize=11, labelpad=10)
    ax.set_ylabel("SynGO Category Term", fontsize=11)

    plt.xticks(rotation=45, ha="right")
    plt.tight_layout()

    # --- STEP 8: EXPORT ENGINE ---
    if saving_path is not None:
        fig.savefig(saving_path, format="pdf", bbox_inches="tight")
        print(f"Successfully saved editable vector plot to: {saving_path}")

    plt.show()

