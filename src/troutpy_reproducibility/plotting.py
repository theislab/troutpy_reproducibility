def plot_ev_enrichment(
    sdata,
    results_df: pd.DataFrame,
    table_key: str = "structure_table",
    cluster_key: str = "urna_cluster",
    cmap: str = "YlOrRd",
    min_dot_size: float = 50.0,
    max_dot_size: float = 300.0,
    saving_path: str = None,
) -> None:
    """Generates an unbiased dot plot of EV enrichment, automatically recovering

    and visualizing clusters that had zero overlap.

    Parameters:
    -----------
    sdata : SpatialData
        The SpatialData container containing the source table.
    results_df : pd.DataFrame
        The output DataFrame generated by the analyze_sdata_ev_ora function.
    table_key : str, default 'structure_table'
        The key in sdata.tables where the AnnData object resides.
    cluster_key : str, default 'urna_cluster'
        The customizable obs column defining the groups/structures.
    cmap : str, default 'YlOrRd'
        Any valid matplotlib/seaborn colormap string (e.g., 'viridis',
        'magma', 'Blues', 'flare').
    min_dot_size : float, default 50.0
        The visual display size for the smallest cluster marker count.
    max_dot_size : float, default 300.0
        The visual display size for the largest cluster marker count.
    saving_path : str, optional
        File path string where the generated PDF plot should be saved.
        If None, the plot is not saved.
    """
    # 1. Fetch all unique clusters from the original spatial data table
    if table_key not in sdata.tables:
        raise KeyError(f"'{table_key}' not found in sdata.tables.")

    all_clusters = [
        c
        for c in sdata.tables[table_key].obs[cluster_key].unique()
        if pd.notna(c)
    ]

    # 2. Calculate the Enrichment Ratio on a copy to preserve the source dataframe
    plot_df = results_df.copy()
    plot_df["enrichment_ratio"] = (
        plot_df["ev_overlap_count"] / plot_df["expected_overlap"]
    )

    # 3. Align and append the missing zero-overlap clusters
    existing_clusters = set(plot_df["cluster"])
    missing_clusters = [c for c in all_clusters if c not in existing_clusters]

    missing_rows = []
    for cluster in missing_clusters:
        missing_rows.append(
            {
                "cluster": cluster,
                "cluster_marker_count": 0,
                "ev_overlap_count": 0,
                "expected_overlap": 0,
                "p_value": 1.0,
                "fdr_bh": 1.0,
                "minus_log10_fdr": 0.0,
                "enrichment_ratio": 0.0,
                "overlapping_genes": "None",
            }
        )

    if missing_rows:
        plot_df = pd.concat([plot_df, pd.DataFrame(missing_rows)], ignore_index=True)

    # Sort so zero-enrichment clusters sit cleanly at the bottom
    plot_df = plot_df.sort_values("enrichment_ratio", ascending=True).copy()

    # 4. Critical: Compress marker counts into a tight visual window using MinMax Scaling
    counts = plot_df["cluster_marker_count"].values
    max_c, min_c = counts.max(), counts.min()

    if max_c == min_c:
        # Avoid dividing by zero if all clusters have identical counts
        dot_sizes = np.repeat((min_dot_size + max_dot_size) / 2, len(counts))
    else:
        # Scale to a 0-1 range, then map to your explicit dot size constraints
        normalized_counts = (counts - min_c) / (max_c - min_c)
        dot_sizes = min_dot_size + (
            normalized_counts * (max_dot_size - min_dot_size)
        )

    # --- PLOTTING ---
    fig, ax = plt.subplots(figsize=(7, 5.5))
    sns.set_theme(style="whitegrid")

    scatter = ax.scatter(
        x=plot_df["enrichment_ratio"],
        y=plot_df["cluster"].astype(str),
        s=dot_sizes,  # Controlled, non-oscillating tight scale
        c=plot_df["minus_log10_fdr"],
        cmap=cmap,  # Variable colormap parameter
        edgecolors="black",
        linewidths=0.8,
        vmin=0,
    )

    # Background random expectation line
    ax.axvline(
        x=1.0,
        color="gray",
        linestyle="--",
        alpha=0.6,
        label="Random Expectation Baseline",
    )

    # Colorbar configuration
    cbar = fig.colorbar(scatter, ax=ax)
    cbar.set_label("-log10(FDR Adjusted P-value)", fontsize=11)

    # Clean manual Legend Generation for the normalized dot sizes
    # Create 4 clean intervals between the min and max raw counts
    legend_labels = np.linspace(min_c, max_c, num=4, dtype=int)
    legend_sizes = np.linspace(min_dot_size, max_dot_size, num=4)

    legend_markers = [
        ax.scatter(
            [],
            [],
            s=sz,
            c="gray",
            alpha=0.6,
            edgecolors="black",
            linewidths=0.8,
        )
        for sz in legend_sizes
    ]

    ax.legend(
        legend_markers,
        legend_labels,
        loc="lower right",
        title="Total Cluster Markers (N)",
        frameon=True,
    )

    ax.set_xlabel("Enrichment Ratio (Observed / Expected Overlap)", fontsize=12)
    ax.set_ylabel(f"Cluster Profile ({cluster_key})", fontsize=12)
    ax.set_title(
        f"Unbiased EV mRNA Enrichment\nGrouping: {cluster_key}",
        fontsize=14,
        pad=15,
    )

    plt.tight_layout()

    # Save logic
    if saving_path is not None:
        # Use bbox_inches="tight" to prevent legend or labels from getting cut off
        fig.savefig(saving_path, format="pdf", bbox_inches="tight")

    plt.show()
