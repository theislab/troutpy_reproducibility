def plot_transcript_distributions(
    data_dict: dict, mode: str = "all", outdir: str = "."
) -> None:
    """Generates and saves specific quality control figures based on the selected mode.

    Parameters:
    -----------
    data_dict : dict
        The output dictionary from compute_transcript_distributions.
    mode : str, default 'all'
        Options:
            - 'all'       : Generates and saves all 3 figures.
            - 'ranges'    : Generates only Figure 1 (Grouped Bar Chart).
            - 'histogram' : Generates only Figure 2 (Overlaid Density Histogram).
            - 'cdf'       : Generates only Figure 3 (Empirical CDF plot).
    outdir : str, default '.'
        The directory path where output PDF files will be saved.
    """
    valid_modes = ["all", "ranges", "histogram", "cdf"]
    if mode not in valid_modes:
        raise ValueError(f"Invalid mode '{mode}'. Choose from: {valid_modes}")

    os.makedirs(outdir, exist_ok=True)

    # Unpack parsed data objects
    cell_counts = data_dict["cell_counts"]
    fragment_counts = data_dict["fragment_counts"]
    df_cells = data_dict["df_cells"]
    df_fragments = data_dict["df_fragments"]
    ks_stat = data_dict["ks_stat"]
    ks_p = data_dict["ks_p"]

    # ─────────────────────────────────────────────────────────────────────────
    # FIGURE 1: Grouped Bar Chart ("ranges")
    # ─────────────────────────────────────────────────────────────────────────
    if mode in ["all", "ranges"]:
        fig1, ax1 = plt.subplots(figsize=(4, 4))
        n_bins = len(df_cells)
        x = np.arange(n_bins)
        w = 0.42

        bars_f = ax1.bar(
            x - w / 2,
            df_fragments["pct"],
            w,
            color=FRAGMENT_COLOR,
            label=f"Fragments (n={len(fragment_counts):,})",
            alpha=0.88,
            edgecolor="white",
            linewidth=0.9,
        )
        bars_c = ax1.bar(
            x + w / 2,
            df_cells["pct"],
            w,
            color=CELL_COLOR,
            label=f"Cells (n={len(cell_counts):,})",
            alpha=0.88,
            edgecolor="white",
            linewidth=0.9,
        )

        for bars, df in [(bars_f, df_fragments), (bars_c, df_cells)]:
            for bar, (_, row) in zip(bars, df.iterrows()):
                h = bar.get_height()
                if h > 0.5:
                    ax1.text(
                        bar.get_x() + bar.get_width() / 2,
                        h + 0.25,
                        f"{int(row['n']):,}",
                        ha="center",
                        va="bottom",
                        fontsize=7,
                        color="#444",
                    )

        ax1.set_xticks(x)
        ax1.set_xticklabels(df_cells["range"], rotation=30, ha="right")
        ax1.set_ylabel("% of observations")
        ax1.set_xlabel("Transcripts per observation")
        ax1.set_title(
            "Transcript Count Distribution by Range",
            fontweight="bold",
            pad=10,
        )
        ax1.legend(frameon=False)
        ax1.yaxis.set_major_formatter(mticker.FormatStrFormatter("%.0f%%"))
        ax1.yaxis.grid(True, color=GRID_COLOR, linewidth=0.7, zorder=0)
        ax1.set_axisbelow(True)

        fig1.text(
            0.99,
            0.01,
            f"KS: D={ks_stat:.3f}, p={ks_p:.2e}",
            ha="right",
            va="bottom",
            fontsize=8,
            color="#888",
            style="italic",
        )
        fig1.tight_layout()
        fig1_path = os.path.join(outdir, "fig1_transcript_ranges.pdf")
        fig1.savefig(fig1_path, dpi=150, bbox_inches="tight")
        print(f"Saved → {fig1_path}")

    # ─────────────────────────────────────────────────────────────────────────
    # FIGURE 2: Overlaid Histogram ("histogram")
    # ─────────────────────────────────────────────────────────────────────────
    if mode in ["all", "histogram"]:
        fig2, ax2 = plt.subplots(figsize=(5, 5))
        hist_bins = np.linspace(0, 1000, 60)

        ax2.hist(
            fragment_counts.clip(max=1000),
            bins=hist_bins,
            density=True,
            color=FRAGMENT_COLOR,
            alpha=0.55,
            label=f"Fragments (n={len(fragment_counts):,})",
            edgecolor="none",
        )
        ax2.hist(
            cell_counts.clip(max=1000),
            bins=hist_bins,
            density=True,
            color=CELL_COLOR,
            alpha=0.55,
            label=f"Cells (n={len(cell_counts):,})",
            edgecolor="none",
        )

        ax2.set_xlabel("Total transcripts per observation (capped at 1,000)")
        ax2.set_ylabel("Density")
        ax2.set_title(
            "Transcript Count Histogram — Fragments vs Cells",
            fontweight="bold",
            pad=10,
        )
        ax2.legend(frameon=False)
        ax2.xaxis.set_major_formatter(
            mticker.FuncFormatter(lambda v, _: f"{int(v):,}")
        )
        ax2.yaxis.grid(True, color=GRID_COLOR, linewidth=0.7, zorder=0)
        ax2.set_axisbelow(True)

        fig2.tight_layout()
        fig2_path = os.path.join(outdir, "fig2_transcript_histogram.pdf")
        fig2.savefig(fig2_path, dpi=150, bbox_inches="tight")
        print(f"Saved → {fig2_path}")

    # ─────────────────────────────────────────────────────────────────────────
    # FIGURE 3: Empirical CDF ("cdf")
    # ─────────────────────────────────────────────────────────────────────────
    if mode in ["all", "cdf"]:
        fig3, ax3 = plt.subplots(figsize=(5, 5))

        for arr, label, color in [
            (
                fragment_counts,
                f"Fragments (n={len(fragment_counts):,})",
                FRAGMENT_COLOR,
            ),
            (cell_counts, f"Cells (n={len(cell_counts):,})", CELL_COLOR),
        ]:
            s = np.sort(arr)
            cdf = np.arange(1, len(s) + 1) / len(s) * 100
            ax3.plot(s, cdf, color=color, lw=2, label=label, alpha=0.9)

        ax3.set_xlim(0, 1000)
        ax3.set_ylim(0, 100)
        ax3.set_xlabel("Total transcripts per observation")
        ax3.set_ylabel("Cumulative % of observations")
        ax3.set_title(
            "Empirical CDF — Fragments vs Cells", fontweight="bold", pad=10
        )
        ax3.legend(frameon=False)
        ax3.yaxis.set_major_formatter(mticker.FormatStrFormatter("%.0f%%"))
        ax3.xaxis.set_major_formatter(
            mticker.FuncFormatter(lambda v, _: f"{int(v):,}")
        )
        ax3.grid(True, color=GRID_COLOR, linewidth=0.7)
        ax3.set_axisbelow(True)

        ax3.text(
            0.99,
            0.02,
            "x-axis capped at 1,000; y-axis shows % of all observations",
            transform=ax3.transAxes,
            ha="right",
            va="bottom",
            fontsize=8,
            color="#888",
            style="italic",
        )

        fig3.tight_layout()
        fig3_path = os.path.join(outdir, "fig3_transcript_cdf.pdf")
        fig3.savefig(fig3_path, dpi=150, bbox_inches="tight")
        print(f"Saved → {fig3_path}")

    plt.show()

