def plot_structure_circularity(
    sdata,
    table_key: str = "structure_table",
    group_key: str = "structure_type",
    figsize: tuple = (8, 5),
    saving_path: str = None,
) -> None:
    """Generates a horizontal hybrid violin/box plot visualizing circularity distributions,

    sorted in decreasing order of mean circularity, and colored using the Scanpy .uns palette.

    Parameters:
    -----------
    sdata : SpatialData
        The SpatialData object containing the structure data.
    table_key : str, default 'structure_table'
        The key in sdata.tables where the AnnData object resides.
    group_key : str, default 'structure_type'
        The obs column inside the table defining structure groups.
    figsize : tuple, default (6, 5)
        The explicit dimensions (width, height) of the figure.
    saving_path : str, optional
        File path string where the generated PDF plot should be saved.
    """
    # 1. Validate table and columns
    if table_key not in sdata.tables:
        raise KeyError(f"'{table_key}' not found in sdata.tables.")

    adata = sdata.tables[table_key]
    obs_df = adata.obs

    if "circularity" not in obs_df.columns:
        raise KeyError(
            f"'circularity' column not found in sdata.tables['{table_key}'].obs"
        )
    if group_key not in obs_df.columns:
        raise KeyError(
            f"Grouping key '{group_key}' not found in sdata.tables['{table_key}'].obs."
        )

    # 2. Extract and clean data
    plot_df = obs_df[[group_key, "circularity"]].dropna().copy()
    plot_df[group_key] = plot_df[group_key].astype(str)

    # 3. Determine decreasing order by mean circularity
    sorted_order = (
        plot_df.groupby(group_key)["circularity"]
        .mean()
        .sort_values(ascending=False)
        .index.tolist()
    )

    # 4. Extract Scanpy colors from .uns dynamically
    uns_color_key = f"{group_key}_colors"
    custom_palette = None

    if uns_color_key in adata.uns:
        # Scanpy links .uns colors to the positional order of the categorical type categories
        if hasattr(obs_df[group_key], "cat"):
            categories = list(obs_df[group_key].cat.categories)
            raw_colors = list(adata.uns[uns_color_key])
            color_map = dict(zip(categories, raw_colors))
            # Reorder palette to align perfectly with our mean circularity sort
            custom_palette = {cat: color_map.get(cat, "gray") for cat in sorted_order}
    
    if custom_palette is None:
        print(f"⚠️ Track '{uns_color_key}' not found in .uns. Falling back to default 'Set2'.")
        custom_palette = "Set2"

    # --- PLOTTING ---
    sns.set_theme(style="whitegrid")
    fig, ax = plt.subplots(figsize=figsize)

    # Render horizontal hybrid violin plot (flipped x and y axes)
    sns.violinplot(
        data=plot_df,
        y=group_key,
        x="circularity",
        order=sorted_order,
        hue=group_key,
        palette=custom_palette,
        inner="box",  # Embedded mini boxplot markers
        linewidth=1.2,
        ax=ax,
        legend=False,
    )

    # --- STYLE REFINEMENTS ---
    ax.set_title(
        "Structure Circularity Profile",
        fontsize=14,
        pad=15,
        weight="bold",
    )
    ax.set_ylabel("Structure Type", fontsize=12)
    ax.set_xlabel("Circularity Score (1.0 = Perfect Circle)", fontsize=12, labelpad=10)

    # Circularity naturally maps between 0 and 1; pad limits slightly for clean viewing
    ax.set_xlim(-0.05, 1.05)

    plt.tight_layout()

    # --- EXPORT ENGINE ---
    if saving_path is not None:
        fig.savefig(saving_path, format="pdf", bbox_inches="tight")
        print(f"Successfully saved editable vector plot to: {saving_path}")

    plt.show()




